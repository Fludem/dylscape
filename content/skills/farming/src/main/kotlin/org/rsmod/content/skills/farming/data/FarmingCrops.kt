/**
 * Every crop that can go in the ground, with the varbit states the client draws it at.
 *
 * The state numbers are **read out of the cache**, not invented: each patch multiloc lists 256
 * child locs, and their internal names spell the lifecycle out (`potato_seed`, `potato_1`..`_3`,
 * `potato_fullygrown`). `FarmingCropStateTest` re-derives them from the live cache and fails if
 * this table drifts.
 *
 * The level and xp figures are the live OSRS ones. [cycleMinutes] is the vanilla growth-stage
 * length for the crop's patch type; [FarmingRates.GROWTH_SPEEDUP] is what makes this server faster
 * than the real game, and it is applied in one place so the table below stays comparable to the
 * wiki.
 *
 * Growth is `growthStages` transitions of `cycleMinutes` each, which reproduces the real totals
 * exactly -- a magic tree is 12 x 40 minutes, a redberry bush 5 x 20.
 */
public class FarmingCrop(
    public val cropName: String,
    public val kind: PatchKind,
    public val seed: ObjType,
    public val produce: ObjType?,
    public val level: Int,
    public val plantXp: Double,
    public val harvestXp: Double,
    public val checkXp: Double,
    public val cycleMinutes: Int,
    public val model: HarvestModel,
    public val regrowMinutes: Int,
    public val baseLives: Int,
    /** Varbit value the moment the seed goes in. */
    public val seedState: Int,
    /** Stage transitions from [seedState] to fully grown. */
    public val growthStages: Int,
    /** State wearing `Check-health`, or -1 when the crop has no such step. */
    public val checkState: Int,
    /** Grown with nothing left to take (`Clear`/`Chop down`), or -1 when the patch just empties. */
    public val grownState: Int,
    /** Indexed by `produceLeft - 1`; empty for crops that only ever pay out check-health xp. */
    public val harvestStates: IntArray,
    /** Left behind by a felled tree, or -1. */
    public val stumpState: Int,
) {
    public val maxProduce: Int
        get() = harvestStates.size

    /** The state a freshly grown crop is shown at, before anything has been taken from it. */
    public val fullyGrownState: Int
        get() = if (checkState != -1) checkState else harvestStates.lastOrNull() ?: grownState
}

