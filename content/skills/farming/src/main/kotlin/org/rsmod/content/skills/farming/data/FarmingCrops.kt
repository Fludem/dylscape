    /**
     * Keyed on the raw obj id: `find()` hands back a `HashedObjType` while the runtime hands
     * scripts an `UnpackedObjType`, and the two never compare equal.
     *
     * Resolved lazily because a reference has no id until the server boots and binds it, and this
     * table is loaded by plain unit tests that never boot one.
     */
    private val bySeed: Map<Int, FarmingCrop> by lazy { all.associateBy { it.seed.id } }

    public fun forSeed(objId: Int): FarmingCrop? = bySeed[objId]

    public fun of(kind: PatchKind): List<FarmingCrop> = all.filter { it.kind == kind }
